-- Tạo cơ sở dữ liệu QL_SINHVIEN
CREATE DATABASE QL_SINHVIEN;
GO
-- Sử dụng cơ sở dữ liệu QL_SINHVIEN
USE QL_SINHVIEN;
GO

-- Tạo bảng KHOA
CREATE TABLE KHOA (
    MAKH VARCHAR(10),
    TENKH NVARCHAR(50),
	CONSTRAINT PK_KHOA PRIMARY KEY(MAKH)
);

-- Tạo bảng LOP
CREATE TABLE LOP (
    MALOP VARCHAR(10),
    TENLOP NVARCHAR(50),
    SISO INT,
    LOPTRUONG NVARCHAR(10),
    MAKH VARCHAR(10),
	CONSTRAINT PK_LOP PRIMARY KEY(MALOP),
    CONSTRAINT FK_LOP FOREIGN KEY (MAKH) REFERENCES KHOA(MAKH)
);

-- Tạo bảng SINHVIEN
CREATE TABLE SINHVIEN (
    MASV VARCHAR(10),
    HOTEN NVARCHAR(50),
    NGSINH DATE,
    GTINH NVARCHAR(3),
    DCHI NVARCHAR(100),
    MALOP VARCHAR(10),
	CONSTRAINT PK_SINHVIEN PRIMARY KEY(MASV),
	CONSTRAINT FK_SINHVIEN FOREIGN KEY (MALOP) REFERENCES LOP(MALOP)
);


-- Tạo bảng GIANGVIEN
CREATE TABLE GIANGVIEN (
    MAGV VARCHAR(10),
    TENGV NVARCHAR(50),
    MAKH VARCHAR(10),
    CONSTRAINT PK_GIANGVIEN PRIMARY KEY(MAGV),
	CONSTRAINT FK_GIANGVIEN FOREIGN KEY (MAKH) REFERENCES KHOA(MAKH)
);

-- Tạo bảng MONHOC
CREATE TABLE MONHOC (
    MAMH VARCHAR(10),
    TENMH NVARCHAR(50),
    SOTC INT,
	CONSTRAINT PK_MONHOC PRIMARY KEY(MAMH),
);

-- Tạo bảng DIEM
CREATE TABLE DIEM (
    MASV VARCHAR(10),
    MAMH VARCHAR(10),
    LANTHI INT,
    DIEMTHI FLOAT,
    CONSTRAINT PK_DIEM PRIMARY KEY (MASV, MAMH, LANTHI),
    CONSTRAINT FK_DIEM FOREIGN KEY (MASV) REFERENCES SINHVIEN(MASV),
    CONSTRAINT FK_DIEM2 FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH)
);

-- Tạo bảng GIANGDAY
CREATE TABLE GIANGDAY (
    MAGV VARCHAR(10),
    MAMH VARCHAR(10),
    NAMHOC NVARCHAR(10),
    HOCKY NVARCHAR(5),
    CONSTRAINT PK_GIANGDAY PRIMARY KEY (MAGV, MAMH, NAMHOC, HOCKY),
    CONSTRAINT FK_GIANGDAY FOREIGN KEY (MAGV) REFERENCES GIANGVIEN(MAGV),
    CONSTRAINT FK_GIANGDAY2 FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH)
);

-- Tạo bảng THANNHAN
CREATE TABLE THANNHAN (
    MATN VARCHAR(10),
    HOTEN NVARCHAR(50),
    GIOITINH NVARCHAR(3),
	CONSTRAINT PK_THANNHAN PRIMARY KEY(MATN)
);

-- Tạo bảng QUANHE
CREATE TABLE QUANHE (
    MATN VARCHAR(10),
    MASV VARCHAR(10),
    QUANHE NVARCHAR(20),
    CONSTRAINT PK_QUANHE PRIMARY KEY (MATN, MASV),
    CONSTRAINT FK_QUANHE FOREIGN KEY (MATN) REFERENCES THANNHAN(MATN),
    CONSTRAINT FK_QUANHE2 FOREIGN KEY (MASV) REFERENCES SINHVIEN(MASV)
);
