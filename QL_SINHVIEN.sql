--TAO BẢNG ÃO LƯU TRỮ DANH SÁCH SV (MASV VÀ HOTEN) , TÊN LOP

CREATE VIEW DANHSACHSINHVIEN AS
SELECT SV.MASV,SV.HOTEN,LH.TENLOP
FROM SINHVIEN SV
JOIN LOP LH ON SV.MALOP=LH.MALOP;

--liet ke DS SINH VIEN Ơ VUNGTAU

SELECT MASV,HOTEN
FROM SINHVIEN
WHERE DCHI=N'Vũng Tàu';

--SO TC MON TOAN ROI RAC
SELECT SOTC
FROM MONHOC
WHERE TENMH=N'Toán rời rạc';

--danh sach lop thuoc khoa cong nghe tt
SELECT L.TENLOP
FROM LOP L
JOIN KHOA K ON L.MAKH = K.MAKH
WHERE K.TENKH = N'Công Nghệ Thông Tin';

--SV co ho nguyễn
SELECT MASV,HOTEN
FROM SINHVIEN
WHERE HOTEN LIKE N'NGUYỄN%'

---LK DS TEN KHOA VÀ SỐ LƯỢNG SV TỪNG KHOA
SELECT TENKH, COUNT(MALOP) AS N'TỔNG SỐ LỚP'
FROM KHOA,LOP
WHERE KHOA.MAKH=LOP.MAKH
GROUP BY TENKH

---LIET KE TENLOP VA SL SV TUNG LOP

SELECT TENLOP,(SELECT COUNT(*) 
				FROM SINHVIEN
				WHERE SINHVIEN.MALOP=LOP.MALOP) AS SLSV
FROM LOP

---LIETKE DS TEN KHOA BA SL SV TUNG KHOA , SAP XEP KHOA THEO SLSV TANG DAN
SELECT TENKH,(SELECT COUNT(*) 
				FROM LOP
				WHERE LOP.MAKH=KHOA.MAKH AND EXISTS (SELECT 1 FROM SINHVIEN S WHERE S.MALOP = LOP.MALOP)
				)AS SLSV  
FROM KHOA
ORDER BY SLSV ASC; 

--LIET KÊ MÃ SV HỌ TÊN ĐIỂM TB
SELECT MASV,HOTEN,(SELECT AVG(DIEMTHI)
					FROM DIEM
					)AS DTB
FROM SINHVIEN

--CHO BIET HO TEN VA TONG SO MON SV NAM DA HOC
SELECT S.HOTEN,(SELECT COUNT(DISTINCT D.MAMH)
						FROM DIEM D
						WHERE D.MASV=S.MASV
				)AS TONGSOMON
FROM SINHVIEN S
WHERE S.GTINH=N'Nam'; 





