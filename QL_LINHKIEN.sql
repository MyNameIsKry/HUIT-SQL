-- câu 15: Tên NSX và số LK đã bán của từng NSX

SELECT NSX, lk.TENLK, COUNT(lk.MALK) AS 'SỐ LƯỢNG'
FROM LINHKIEN lk, CHITIETHOADON cthd
WHERE lk.MALK = cthd.MALK
GROUP BY NSX, lk.TENLK;

-- câu 16: MAHD và tổng tiền từng HD

SELECT hd.MAHD, SUM(hd.TONGTIEN) AS 'TỔNG TIỀN'
FROM HOADON hd, CHITIETHOADON cthd
WHERE hd.MAHD = cthd.MAHD
GROUP BY hd.MAHD;

-- câu 17: Danh sách tên KH và MAHD có tổng tiền > 1m

SELECT kh.TENKH, hd.MAHD, SUM(hd.TONGTIEN) AS 'TỔNG TIỀN'
FROM HOADON hd, CHITIETHOADON cthd, KHACHHANG kh
WHERE hd.MAHD = cthd.MAHD AND hd.MAKH = kh.MAKH
GROUP BY kh.TENKH, hd.MAHD;

-- câu 18: Mỗi loại LK có bao nhieu LK

SELECT LOAILK.MALOAI, COUNT(MALK)
FROM LINHKIEN, LOAILK
WHERE LINHKIEN.MALOAI = LOAILK.MALOAI
GROUP BY LOAILK.MALOAI;

-- câu 19: MAHD có số lượng LK > 10

SELECT MAHD, SUM(SOLUONG)
FROM CHITIETHOADON
GROUP BY MAHD
HAVING SUM(SOLUONG)>10

