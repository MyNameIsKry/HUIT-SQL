-- câu 11: trong 05/2016 đã lập bao nhiêu đơn hàng:

SELECT hd.MAHD, COUNT(hd.MAHD) AS 'Số lượng đơn'
FROM CHITIETHOADON, HOADON hd
WHERE CHITIETHOADON.MAHD = hd.MAHD AND NGAYHD LIKE '2016-05-%'
GROUP BY hd.MAHD;

