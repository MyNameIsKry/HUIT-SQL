-- Câu 1: Cập nhật tổng tiền cho mỗi hóa đơn = tổng hóa đơn (số lượng x đơn giá)

UPDATE HOADON
SET TONGTIEN = (
	SELECT SUM(SOLUONG * DONGIA)
	FROM CHITIETHOADON
	WHERE CHITIETHOADON.MAHD = HOADON.MAHD
)

-- câu 2: cho biết tên linh kiện nsx là genius và có đơn vị tính là cái

SELECT TENLK
FROM LINHKIEN
WHERE NSX='Genius' AND DVT=N'Cái';

-- câu 3: thông tin liên kiện có TGBH là 24 tháng

SELECT *
FROM LINHKIEN
WHERE TGBH=24;

-- câu 4: hóa đơn nào đc lập trong 06/2016

SELECT *
FROM HOADON
WHERE NGAYHD LIKE '2016-06-%';

-- câu 5: Tên và DVT LK có đơn giá > 1000000

SELECT TENLK, DVT
FROM CHITIETHOADON, LINHKIEN
WHERE CHITIETHOADON.MALK = LINHKIEN.MALK AND DONGIA >= 1000000;

-- câu 6: thông tin MALK, TENLK, NSX, DVT được bán trước ngày 31/05/2015

SELECT LINHKIEN.MALK, TENLK, NSX, DVT
FROM LINHKIEN, CHITIETHOADON, HOADON
WHERE CHITIETHOADON.MALK = LINHKIEN.MALK AND HOADON.MAHD = CHITIETHOADON.MAHD
AND HOADON.NGAYHD < '2015-05-31';

-- câu 7: Danh sách các KH mua LK trong 06/2016 có địa chỉ ở TP.HCM

SELECT KHACHHANG.*
FROM KHACHHANG, CHITIETHOADON, HOADON
WHERE KHACHHANG.MAKH = HOADON.MAKH AND HOADON.MAHD = CHITIETHOADON.MAHD
AND KHACHHANG.DCHI = 'TP.HCM';

-- câu 8: cho biết tổng số lượng LK của HD007

SELECT MAHD, SUM(SOLUONG) AS 'So Luong'
FROM CHITIETHOADON
WHERE MAHD='HD007'
GROUP BY MAHD;

-- câu 9: trog tháng 5/2016 có bao nhiêu khách ở Tây Ninh tới mua hàng

SELECT COUNT(MAKH) as N'Số lượng khách'
FROM KHACHHANG
WHERE MAKH IN (
	SELECT HOADON.MAKH
	FROM HOADON
	WHERE NGAYHD LIKE '2016-05-%'
) AND KHACHHANG.DCHI = 'Tây Ninh';

-- câu 10: DTHOAI và DCHI của KH001 

