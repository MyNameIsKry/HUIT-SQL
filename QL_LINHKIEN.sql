CREATE TABLE LOAILK (
	MALOAI CHAR(10),
	TENLOAI NVARCHAR(50),
	CONSTRAINT PK_MALOAI PRIMARY KEY(MALOAI)
)

CREATE TABLE LINHKIEN (
	MALK CHAR(10),
	TENLK NVARCHAR(50),
	NGAYSX DATE,
	TGBH INT,
	MALOAI CHAR(10),
	NSX NVARCHAR(20),
	DVT NVARCHAR(10),
	CONSTRAINT PK_MALK PRIMARY KEY(MALK),
	CONSTRAINT FK_MALOAI FOREIGN KEY(MALOAI) REFERENCES LOAILK(MALOAI)
)

CREATE TABLE KHACHHANG (
	MAKH CHAR(10),
	TENKH NVARCHAR(50),
	DCHI NVARCHAR(50),
	DTHOAI CHAR(11),
	CONSTRAINT PK_MAKH PRIMARY KEY(MAKH)
)

CREATE TABLE HOADON (
	MAHD CHAR(10),
	NGAYHD DATE,
	MAKH CHAR(10),
	TONGTIEN FLOAT NULL,
	CONSTRAINT PK_MAHD PRIMARY KEY(MAHD),
	CONSTRAINT FK_MAKH_2 FOREIGN KEY(MAKH) REFERENCES KHACHHANG(MAKH)
)

CREATE TABLE CHITIETHOADON (
	MAHD CHAR (10),
	MALK CHAR (10),
	SOLUONG INT,
	DONGIA FLOAT,
	CONSTRAINT PK_MAHD_MAKH PRIMARY KEY(MAHD, MALK),
	CONSTRAINT FK_MAHD_2 FOREIGN KEY (MAHD) REFERENCES HOADON(MAHD),
	CONSTRAINT FK_MALK FOREIGN KEY (MALK) REFERENCES LINHKIEN(MALK)
)

